import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
const root = process.argv[2];
const files = [];
const walk = (d) => { for (const n of readdirSync(d)) { const p = join(d, n); statSync(p).isDirectory() ? walk(p) : /\.(tsx|ts|css)$/.test(n) && files.push(p); } };
walk(root);
const text = files.map((f) => readFileSync(f, 'utf8')).join('\n');
const tally = (re) => { const m = {}; for (const x of text.match(re) || []) m[x] = (m[x] || 0) + 1; return Object.entries(m).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${v} ${k}`).join(' | '); };
console.log('files', files.length);
console.log('arbitrary sizes:', tally(/text-\[[0-9.]+(px|rem)\]/g));
console.log('named sizes:', tally(/\btext-(xs|sm|base|lg|xl|2xl|3xl|4xl|5xl)\b/g));
console.log('durations:', tally(/duration-(\d+|\[[^\]]+\])/g));
console.log('transition kinds:', tally(/\btransition(-[a-z]+|-\[[^\]]+\])?\b/g));
console.log('tracking:', tally(/tracking-\[[-0-9.a-z]+\]/g));
console.log('radii classes:', tally(/\brounded(-[a-z0-9]+)?\b/g));
console.log('var(--duration) refs:', (text.match(/var\(--duration/g) || []).length);
console.log('text-white/bg-white:', (text.match(/\b(text|bg)-white\b/g) || []).length);
console.log('hex in tsx:', tally(/#[0-9a-fA-F]{6}\b/g));
console.log('text-balance:', (text.match(/text-balance/g) || []).length);
console.log('mono label strings:', (text.match(/font-mono text-\[1[01]px\][^'"`]*uppercase[^'"`]*tracking/g) || []).length);
console.log('eyebrow:', (text.match(/className="eyebrow"|eyebrow="/g) || []).length);
console.log('h-8 w-8 / size sm:', (text.match(/size="sm"/g) || []).length);
